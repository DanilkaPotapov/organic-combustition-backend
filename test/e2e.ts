import 'reflect-metadata';
import 'dotenv/config';
import * as assert from 'assert/strict';
import { Test } from '@nestjs/testing';
import { DataSource } from 'typeorm';
import * as request from 'supertest';
import { ConfigService } from '@nestjs/config';
import { AppModule } from '../src/app.module';
import { setup } from '../src/setup';
import { SessionsService } from '../src/shared/sessions.service';
import { MinioService } from '../src/organic_compounds/services/minio.service';
import { User } from '../src/users/entities/user.entity';
import { OrganicCompound } from '../src/organic_compounds/entities/organic_compound.entity';
import { OrganicCompoundLike } from '../src/organic_compounds/entities/organic_compound_like.entity';
import { CreateOrganicCompoundsLab3Schema1791417600000 } from '../src/database/migrations/1791417600000-CreateOrganicCompoundsLab3Schema';
import { AddLab4SessionsAuth1793700000000 } from '../src/database/migrations/1793700000000-AddLab4SessionsAuth';
import { join } from 'path';

async function run() {
  const isolated = process.env.TEST_ISOLATED === 'true';
  const builder = Test.createTestingModule({ imports: [AppModule] });
  if (isolated) {
    const { newDb, DataType } = require('pg-mem');
    const db = newDb({ autoCreateForeignKeyIndices: true });
    db.public.registerFunction({ name: 'current_database', returns: DataType.text, implementation: () => 'lab4_test' });
    db.public.registerFunction({ name: 'version', returns: DataType.text, implementation: () => 'PostgreSQL 17' });
    db.public.registerFunction({ name: 'hashtext', args: [DataType.text], returns: DataType.integer, implementation: () => 1 });
    db.public.registerFunction({ name: 'pg_advisory_xact_lock', args: [DataType.integer], returns: DataType.integer, implementation: () => 1, impure: true });
    const ds = db.adapters.createTypeormDataSource({ type: 'postgres', entities: [User, OrganicCompound, OrganicCompoundLike], migrations: [CreateOrganicCompoundsLab3Schema1791417600000, AddLab4SessionsAuth1793700000000], synchronize: false });
    await ds.initialize();
    await ds.runMigrations();
    builder.overrideProvider(DataSource).useValue(ds);
    const RedisMock = require('ioredis-mock');
    const sessions = Object.assign(Object.create(SessionsService.prototype), { redis: new RedisMock(), ttl: 3600 });
    builder.overrideProvider(SessionsService).useValue(sessions);
    const media = new MinioService(new ConfigService());
    media.upload = async () => undefined;
    builder.overrideProvider(MinioService).useValue(media);
  }
  const module = await builder.compile();
  const app = module.createNestApplication();
  const spec = setup(app);
  await app.init();
  try {
    const server = app.getHttpServer();
    const send = request(server);
    const first = request.agent(server);
    const second = request.agent(server);
    const tag = Date.now();
    const email = `e2e-${tag}@example.local`;
    const email2 = `e2e-other-${tag}@example.local`;
    const password = 'Potapov123!';
    const publish = { shortDescription: 'Тестовое соединение', carbonCount: 4, hydrogenCount: 10 };
    const cardKeys = ['id','name','shortDescription','imageUrl','videoUrl','carbonCount','hydrogenCount','likeCount','isOwner','isLiked'].sort();
    const checkCard = (card: any) => assert.deepEqual(Object.keys(card).sort(),cardKeys);
    const empty = (res: any) => assert.equal(res.text, '');
    assert.ok(spec.components?.securitySchemes?.cookie);
    assert.ok(spec.paths['/api/organic_compounds/feed']);
    assert.ok(spec.paths['/api/organic_compounds/feed/{id}']);
    const ids = Object.values(spec.paths).flatMap((p: any) => Object.values(p).map((o: any) => o.operationId));
    assert.equal(new Set(ids).size, ids.length);
    await send.get('/api').expect(200);
    empty(await send.get('/api/organic_compounds/draft').expect(401));
    empty(await send.post('/api/organic_compounds').expect(401));
    empty(await send.put('/api/organic_compounds/1/publish').send(publish).expect(401));
    const registered = await send.post('/api/users/register').send({name:'Первый автор',email,password}).expect(201);
    assert.equal(registered.body.role,'user');
    assert.equal(registered.body.passwordHash,undefined);
    await send.post('/api/users/register').send({name:'Второй автор',email:email2,password}).expect(201);
    empty(await send.post('/api/users/register').send({name:'Первый автор',email,password}).expect(409));
    empty(await send.post('/api/users/register').send({name:'Роль',email:'role@example.local',password,role:'moderator'}).expect(400));
    empty(await first.post('/api/users/auth').send({email,password:'wrong123'}).expect(401));
    const login = await first.post('/api/users/auth').send({email,password}).expect(200);
    const cookie = login.headers['set-cookie'][0];
    assert.match(cookie,/HttpOnly/); assert.match(cookie,/SameSite=Lax/);
    const sessionId = cookie.match(/sessionId=([^;]+)/)![1];
    const sessions = app.get(SessionsService);
    assert.equal((await sessions.find(sessionId))?.id,registered.body.id);
    empty(await first.get('/api/organic_compounds/draft').expect(404));
    const created = await first.post('/api/organic_compounds').field('name',`Тест ${tag}`)
      .attach('image',join(__dirname,'../postman/files/organic_compound.png'))
      .attach('video',join(__dirname,'../postman/files/organic_compound.webm')).expect(201);
    assert.deepEqual(Object.keys(created.body),['id']);
    const id = created.body.id;
    const draft = await first.get('/api/organic_compounds/draft').expect(200);
    checkCard(draft.body); assert.equal(draft.body.carbonCount,null); assert.equal(draft.body.shortDescription,null); assert.equal(draft.body.isOwner,1);
    const stored = await app.get(DataSource).getRepository(OrganicCompound).findOneByOrFail({id});
    assert.equal(stored.creatorId,registered.body.id);
    assert.match(stored.imageFileName,/^organic-compound-image-[a-f0-9-]+\.png$/);
    const storedUser = await app.get(DataSource).getRepository(User).findOneByOrFail({id:registered.body.id});
    assert.match(storedUser.passwordHash,/^\$2[aby]\$12\$/);
    await second.post('/api/users/auth').send({email:email2,password}).expect(200);
    empty(await second.put(`/api/organic_compounds/${id}/publish`).send(publish).expect(403));
    empty(await second.delete(`/api/organic_compounds/${id}`).expect(403));
    empty(await first.put(`/api/organic_compounds/${id}/publish`).send({...publish,status:'published'}).expect(400));
    const published = await first.put(`/api/organic_compounds/${id}/publish`).send(publish).expect(200);
    checkCard(published.body); assert.equal(published.body.carbonCount,4);
    const guest = await send.get('/api/organic_compounds?carbonCount=4').expect(200);
    assert.ok(guest.body.some((c:any)=>c.id===id));
    guest.body.forEach((c:any)=>{checkCard(c);assert.equal(c.carbonCount,4);assert.equal(c.isOwner,0);assert.equal(c.isLiked,0);});
    const invalidCookie = await send.get('/api/organic_compounds').set('Cookie','sessionId=invalid').expect(200);
    invalidCookie.body.forEach(checkCard);
    checkCard((await send.get('/api/organic_compounds/feed').expect(200)).body);
    checkCard((await send.get(`/api/organic_compounds/feed/${id}?next=true`).expect(200)).body);
    const liked = await second.post(`/api/organic_compounds/${id}/like`).send({value:1}).expect(200);
    checkCard(liked.body);assert.equal(liked.body.isLiked,1);assert.equal(liked.body.isOwner,0);
    const likedAgain = await second.post(`/api/organic_compounds/${id}/like`).send({value:1}).expect(200);
    assert.equal(likedAgain.body.likeCount,liked.body.likeCount);
    const unliked = await second.post(`/api/organic_compounds/${id}/like`).send({value:0}).expect(200);
    assert.equal(unliked.body.isLiked,0);assert.equal(unliked.body.likeCount,liked.body.likeCount-1);
    empty(await first.post('/api/users/logout').expect(200));
    assert.equal(await sessions.find(sessionId),null);
    empty(await send.get('/api/organic_compounds/draft').set('Cookie',`sessionId=${sessionId}`).expect(401));
    await first.post('/api/users/auth').send({email,password}).expect(200);
    empty(await first.delete(`/api/organic_compounds/${id}`).expect(200));
    empty(await send.get(`/api/organic_compounds/feed/${id}`).expect(404));
    assert.equal((await app.get(DataSource).getRepository(OrganicCompound).findOneByOrFail({id})).status,'deleted');
    console.log(`PASS: миграции, Swagger, регистрация, bcrypt, cookie, сессия, права двух авторов, файлы, черновик, публикация, JSON, лента, лайки, logout, soft delete. Режим: ${isolated?'pg-mem + Redis mock + MinIO mock':'PostgreSQL + Redis + MinIO'}.`);
  } finally { await app.close(); }
}
run().catch((error)=>{console.error(error);process.exitCode=1;});
